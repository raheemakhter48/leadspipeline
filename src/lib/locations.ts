export function getRegionOptions(country: string) {
  return ["All Regions", ...Object.keys(countryLocations[country] ?? {})];
}

export function getCityOptions(country: string, region: string) {
  const regions = countryLocations[country] ?? {};
  if (region === "All Regions") {
    return ["All Cities", ...Object.values(regions).flat()];
  }

  return ["All Cities", ...(regions[region] ?? [])];
}

export function defaultRegion(country: string) {
  return getRegionOptions(country)[0] ?? "All Regions";
}
